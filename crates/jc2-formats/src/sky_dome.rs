//! The native sky dome, the FogGradient colour inputs and the stars (JC2-214; research
//! `research/formats/sky-gradient-next.md`, JC2-151 / JC2-173, probe
//! `research/tools/sky_gradient_probe.py`).
//!
//! * The dome is a 32-triangle cone (`FUN_00a4a220`): radius 100, apex height 100, ring at y = 0.
//!   Its `u` is the azimuth to the sun (0 at local +z, one texel on the far side) and `v` is 1 at the
//!   ring, -0.5 at the apex. [`dome_vertices`] is the vertex list the exe builds.
//! * [`hour_inputs`] is `FUN_00a44d40`: `A`, `B` (u offsets of the two columns, one even column per 1.5
//!   hours) and the blend `f`; [`sky_dome_colour`] is the pixel shader on the CPU (bilinear in
//!   **linear** space, `skygradient_dif.dds` is sampled as sRGB).
//! * [`make_stars`] is `FUN_00a47750` (`srand(1)`, the MSVC `rand`), [`star_alpha_byte`] /
//!   [`star_alpha`] the alpha of `FUN_00a472f0` / `FUN_00a45330`.
//!
//! All of it is native (byte-checked by the probe) except where a function says otherwise.

use crate::weather::Gradient;
use std::f32::consts::PI;

pub const DOME_RADIUS: f32 = 100.0;
pub const DOME_SEGMENTS: usize = 32;
/// The pixel shader clamps `v` to this range before the lookup.
pub const V_MIN: f32 = 0.01;
pub const V_MAX: f32 = 0.99;
/// Number of stars generated by `FUN_00a47750`.
pub const STAR_COUNT: usize = 2000;

/// sRGB decode (the texture view is `_SRGB`, filtering happens after the decode).
pub fn srgb_to_linear(c: f32) -> f32 {
    if c <= 0.04045 {
        c / 12.92
    } else {
        ((c + 0.055) / 1.055).powf(2.4)
    }
}

/// `FUN_00a44d40`: `t = hour / 24 * 16`, `k = floor t`; returns `(A, B, f)`: the u offsets
/// `(k + 0.25) / 16`, `(k + 1.25) / 16` and the blend `f = frac t`.
pub fn hour_inputs(hour: f32) -> (f32, f32, f32) {
    let t = hour.rem_euclid(24.0) * (1.0 / 24.0) * 16.0;
    let k = t.floor();
    let f = (t - k).clamp(0.0, 1.0);
    ((k + 0.25) * 0.0625, (k + 1.25) * 0.0625, f)
}

/// One vertex of the dome: position (local, +z towards the sun) and `(u, v)`.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct DomeVertex {
    pub position: [f32; 3],
    pub uv: [f32; 2],
}

/// `u` of ring vertex `i`: `|theta| / pi / 32`, `theta = 2 pi i / 32` folded into (-pi, pi].
fn ring_u(i: usize) -> f32 {
    let mut th = 2.0 * PI * i as f32 / DOME_SEGMENTS as f32;
    if th > PI {
        th -= 2.0 * PI;
    }
    th.abs() / PI / 32.0
}

fn ring_point(i: usize) -> [f32; 3] {
    let a = 2.0 * PI * i as f32 / DOME_SEGMENTS as f32;
    [DOME_RADIUS * a.sin(), 0.0, DOME_RADIUS * a.cos()]
}

/// The 96 vertices of the cone, three per segment in the exe's order (ring `i`, apex, ring `i+1`).
/// (The exe's sine is a polynomial with an error below 0.001; the exact sine is used here.)
pub fn dome_vertices() -> Vec<DomeVertex> {
    let mut out = Vec::with_capacity(DOME_SEGMENTS * 3);
    for i in 0..DOME_SEGMENTS {
        out.push(DomeVertex {
            position: ring_point(i),
            uv: [ring_u(i), 1.0],
        });
        out.push(DomeVertex {
            position: [0.0, DOME_RADIUS, 0.0],
            uv: [1.0 / 64.0, -0.5],
        });
        out.push(DomeVertex {
            position: ring_point(i + 1),
            uv: [ring_u(i + 1), 1.0],
        });
    }
    out
}

/// `(u, v)` of the dome mesh for a view ray with azimuth `az` (radians from the dome's local +z
/// towards +x) and elevation `elev` (radians): the ray meets the facet `(ring i, apex, ring i+1)`
/// and `u`, `v` are the same affine combination of the vertex values (probe `dome_uv`).
pub fn dome_uv(az: f32, elev: f32) -> (f32, f32) {
    let (az, elev) = (az as f64, elev as f64);
    let r = DOME_RADIUS as f64;
    let d = [elev.cos() * az.sin(), elev.sin(), elev.cos() * az.cos()];
    let seg = std::f64::consts::TAU / DOME_SEGMENTS as f64;
    let th = az.rem_euclid(std::f64::consts::TAU);
    let i = ((th / seg).floor() as usize) % DOME_SEGMENTS;
    let (a0, a1) = (seg * i as f64, seg * (i + 1) as f64);
    let r0 = [r * a0.sin(), 0.0, r * a0.cos()];
    let r1 = [r * a1.sin(), 0.0, r * a1.cos()];
    let ap = [0.0, r, 0.0];
    let det = |a: [f64; 3], b: [f64; 3], c: [f64; 3]| {
        a[0] * (b[1] * c[2] - b[2] * c[1]) - a[1] * (b[0] * c[2] - b[2] * c[0])
            + a[2] * (b[0] * c[1] - b[1] * c[0])
    };
    let c2 = [-(r0[0] - ap[0]), -(r0[1] - ap[1]), -(r0[2] - ap[2])];
    let c3 = [-(r1[0] - ap[0]), -(r1[1] - ap[1]), -(r1[2] - ap[2])];
    let den = det(d, c2, c3);
    let l0 = det(d, ap, c3) / den;
    let l2 = det(d, c2, ap) / den;
    let l1 = 1.0 - l0 - l2;
    let u0 = ring_u(i) as f64;
    let u2 = if i + 1 == DOME_SEGMENTS {
        0.0
    } else {
        ring_u(i + 1) as f64
    };
    let u = l0 * u0 + l1 / 64.0 + l2 * u2;
    let v = l0 - l1 * 0.5 + l2;
    (u as f32, v as f32)
}

/// One texel of the 32 x 128 table as **linear** RGB.
fn linear_texel(g: &Gradient, x: i64, y: i64) -> [f32; 3] {
    let x = x.rem_euclid(g.width as i64) as usize;
    let y = y.clamp(0, g.height as i64 - 1) as usize;
    let t = g.texel(x, y);
    [
        srgb_to_linear(t[0]),
        srgb_to_linear(t[1]),
        srgb_to_linear(t[2]),
    ]
}

/// Bilinear sample in linear space: wrap in `u`, clamp in `v`, texel centres at `(n + 0.5) / size`.
pub fn sample_linear(g: &Gradient, u: f32, v: f32) -> [f32; 3] {
    let x = u * g.width as f32 - 0.5;
    let y = v * g.height as f32 - 0.5;
    let (x0, y0) = (x.floor(), y.floor());
    let (fx, fy) = (x - x0, y - y0);
    let mut out = [0.0; 3];
    for (dy, wy) in [(0, 1.0 - fy), (1, fy)] {
        for (dx, wx) in [(0, 1.0 - fx), (1, fx)] {
            let t = linear_texel(g, x0 as i64 + dx, y0 as i64 + dy);
            for c in 0..3 {
                out[c] += t[c] * wx * wy;
            }
        }
    }
    out
}

/// The native scene colour (linear, 1.0 = display white) of the dome pixel at azimuth `az` from the
/// sun-facing side and elevation `elev` (radians), at `hour`: the pixel shader of `skygradientshader`.
pub fn sky_dome_colour(sky: &Gradient, hour: f32, az: f32, elev: f32) -> [f32; 3] {
    let (a, b, f) = hour_inputs(hour);
    let (u, v) = dome_uv(az, elev);
    let v = v.clamp(V_MIN, V_MAX);
    let ca = sample_linear(sky, u + a, v);
    let cb = sample_linear(sky, u + b, v);
    [
        ca[0] * (1.0 - f) + cb[0] * f,
        ca[1] * (1.0 - f) + cb[1] * f,
        ca[2] * (1.0 - f) + cb[2] * f,
    ]
}

/// `FUN_00a472f0`: `clamp((V.y - 0.1) * 300, 0, 200)` truncated to a byte; `V.y` is the y of the
/// unflipped light vector (`W + 0x260`, the sign of which is inferred to be -toSun, JC2-204).
pub fn star_alpha_byte(light_y: f32) -> u8 {
    let v = (light_y - 0.1) * 300.0;
    v.clamp(0.0, 200.0) as u8
}

/// `FUN_00a45330`: the star pixel alpha `min(byte / 128, 1)`.
pub fn star_alpha(byte: u8) -> f32 {
    (f32::from(byte) * 0.0078125).min(1.0)
}

/// One star of `FUN_00a47750`: the position (direction times distance 100 .. 500) and the size
/// class 2 .. 20 (half a sprite in 720-line pixels).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Star {
    pub position: [f32; 3],
    pub size: f32,
}

/// The statically linked MSVC `rand()`: `state = state * 214013 + 2531011`, `(state >> 16) & 0x7fff`.
struct MsvcRand(u32);

impl MsvcRand {
    fn next(&mut self) -> u32 {
        self.0 = self.0.wrapping_mul(214_013).wrapping_add(2_531_011);
        (self.0 >> 16) & 0x7fff
    }
}

/// `FUN_00a47750`: `srand(1)`, then per star seven `rand()` calls, each mapped to `r = rand *
/// 6.103702e-05 - 1`: three give the direction (normalised unless its squared length is below
/// 1e-6), two the distance `r5 r4 200 + 300`, two the size `|r7 r6| 18 + 2`.
pub fn make_stars(count: usize) -> Vec<Star> {
    let mut rng = MsvcRand(1);
    let mut r = move || rng.next() as f32 * 6.103_702e-5 - 1.0;
    let mut out = Vec::with_capacity(count);
    for _ in 0..count {
        let (a, b, c) = (r(), r(), r());
        let l2 = b * b + a * a + c * c;
        let inv = if l2 - 1e-6 >= 0.0 {
            1.0 / l2.sqrt()
        } else {
            1.0
        };
        let d = [a * inv, b * inv, c * inv];
        let (r4, r5) = (r(), r());
        let dist = r5 * r4 * 200.0 + 300.0;
        let (r6, r7) = (r(), r());
        let size = (r7 * r6).abs() * 18.0 + 2.0;
        out.push(Star {
            position: [dist * d[0], dist * d[1], dist * d[2]],
            size,
        });
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::vfs::GameFs;
    use crate::weather::Atmosphere;

    fn near(a: [f32; 3], b: [f32; 3], tol: f32) -> bool {
        (0..3).all(|i| (a[i] - b[i]).abs() < tol)
    }

    #[test]
    fn hour_mapping_picks_one_even_column_per_one_and_a_half_hours() {
        let (a, b, f) = hour_inputs(6.0);
        assert!((a - 4.25 * 0.0625).abs() < 1e-6 && (b - 5.25 * 0.0625).abs() < 1e-6);
        assert!(f.abs() < 1e-6);
        // 7:30 is the next column
        let (a, _, f) = hour_inputs(7.5);
        assert!((a - 5.25 * 0.0625).abs() < 1e-6 && f.abs() < 1e-5);
        // 22.5 .. 24 blends column 30 into column 0 (A + u wraps)
        let (a, b, f) = hour_inputs(23.25);
        assert!((a - 15.25 * 0.0625).abs() < 1e-6 && (b - 16.25 * 0.0625).abs() < 1e-6);
        assert!((f - 0.5).abs() < 1e-5);
    }

    #[test]
    fn the_dome_is_a_32_triangle_cone_with_the_exes_uv() {
        let v = dome_vertices();
        assert_eq!(v.len(), 96);
        // ring 0 points at local +z with u = 0, the far side (ring 16) has u = 1/32
        assert!((v[0].position[2] - 100.0).abs() < 1e-3 && v[0].uv == [0.0, 1.0]);
        let far = v[16 * 3];
        assert!((far.position[2] + 100.0).abs() < 1e-3);
        assert!((far.uv[0] - 1.0 / 32.0).abs() < 1e-6);
        assert_eq!(v[1].position, [0.0, 100.0, 0.0]);
        assert_eq!(v[1].uv, [1.0 / 64.0, -0.5]);
        // u rises monotonically from the sun side to the far side
        for i in 0..16 {
            assert!(v[(i + 1) * 3].uv[0] > v[i * 3].uv[0]);
        }
    }

    #[test]
    fn the_first_stars_are_the_probes() {
        let s = make_stars(STAR_COUNT);
        assert_eq!(s.len(), 2000);
        let want = [
            ([-271.84, 34.66, -167.16], 2.217),
            ([144.08, 117.47, 89.73], 2.205),
        ];
        for (star, (p, size)) in s.iter().zip(want) {
            for (got, want) in star.position.iter().zip(p) {
                assert!((got - want).abs() < 0.02, "{star:?}");
            }
            assert!((star.size - size).abs() < 0.002, "{star:?}");
        }
        for star in &s {
            assert!((2.0..=20.0).contains(&star.size));
            let d = (star.position.iter().map(|c| c * c).sum::<f32>()).sqrt();
            assert!((100.0..=500.0).contains(&d), "{d}");
        }
    }

    #[test]
    fn the_stars_appear_as_the_sun_sinks_below_the_horizon() {
        // V.y = -toSun.y: alpha 0 until the sun is 5.7 degrees down, 1 from 31.8 degrees
        assert_eq!(star_alpha_byte(0.1), 0);
        assert_eq!(star_alpha_byte(-0.5), 0);
        assert_eq!(star_alpha_byte(0.1 + 128.0 / 300.0 + 0.001), 128);
        assert_eq!(star_alpha_byte(1.0), 200);
        assert_eq!(star_alpha(200), 1.0);
        assert_eq!(star_alpha(64), 0.5);
    }

    /// The fixtures of `research/formats/sky-gradient-next.md` section 2 (linear, 1e-5), on the
    /// retail texture.
    #[test]
    fn the_retail_dome_matches_the_probe_fixtures() {
        let Ok(dir) = std::env::var("JC2_TEST_DIR") else {
            return;
        };
        let Ok(fs) = GameFs::open(dir) else { return };
        let Ok(atm) = Atmosphere::load(&fs) else {
            return;
        };
        let d = std::f32::consts::PI / 180.0;
        let cases = [
            (6.0, 0.0, 0.01, [0.51965, 0.09762, 0.01374]),
            (6.0, 180.0, 0.01, [0.42990, 0.49229, 0.49228]),
            (12.0, 0.0, 0.01, [0.59864, 0.79300, 0.86316]),
            (12.0, 180.0, 0.01, [0.42991, 0.66540, 0.86316]),
            (12.0, 0.0, 89.0, [0.00368, 0.01764, 0.09990]),
            (18.0, 0.0, 0.01, [0.70836, 0.16274, 0.01942]),
            (0.0, 0.0, 10.0, [0.04625, 0.07421, 0.09468]),
        ];
        for (hour, az, el, want) in cases {
            let got = sky_dome_colour(&atm.sky, hour, az * d, el * d);
            assert!(
                near(got, want, 2e-4),
                "{hour} {az} {el}: {got:?} vs {want:?}"
            );
        }
    }
}
